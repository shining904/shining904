def write(n, post, caption):
    d = f"post{n:02d}"
    os.makedirs(d, exist_ok=True)
    with open(f"{d}/post.json", "w") as f:
        json.dump(post, f, ensure_ascii=False, indent=2)
    with open(f"{d}/caption.txt", "w") as f:
        f.write(caption)

